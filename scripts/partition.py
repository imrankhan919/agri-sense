from datetime import date
from sqlalchemy import text
from app.database import engine


def quarters(first_year: int, last_year: int):
    for year in range(first_year, last_year + 1):
        for q in range(4):
            start = date(year, q * 3 + 1, 1)
            end = date(year + 1, 1, 1) if q == 3 else date(year, q * 3 + 4, 1)
            yield f"price_records_{year}_q{q + 1}", start, end


CREATE_PARENT = """
CREATE TABLE price_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 crop_id INTEGER NOT NULL REFERENCES crop(id),
 market_id INTEGER NOT NULL REFERENCES market(id),
 price_date DATE NOT NULL,
 modal_price DOUBLE PRECISION NOT NULL,
 min_price DOUBLE PRECISION NOT NULL,
 max_price DOUBLE PRECISION NOT NULL,
 PRIMARY KEY (id, price_date) -- partition key PK ka hissa hona zaroori hai
) PARTITION BY RANGE (price_date)
"""


COPY_DATA = """
INSERT INTO price_records (id, crop_id, market_id, price_date, modal_price, min_price, max_price)
SELECT id, crop_id, market_id, price_date, modal_price, min_price, max_price
FROM price_records_old"""



def main() -> None:
    with engine.begin() as conn: 
        kind = conn.execute(text("SELECT relkind FROM pg_class WHERE relname = 'price_records'")).scalar()
        if kind == "p":
            print("price_records already partitioned.")
            return
        conn.execute(text("ALTER TABLE price_records RENAME TO price_records_old"))
        conn.execute(text("ALTER INDEX price_records_pkey RENAME TO price_records_old_pkey"))
        conn.execute(text("DROP INDEX IF EXISTS idx_price_crop_market_date"))
        conn.execute(text(CREATE_PARENT))
        for name, start, end in quarters(2024, 2027):
            ddl = f"CREATE TABLE {name} PARTITION OF price_records FOR VALUES FROM ('{start}') TO ('{end}')"
            conn.execute(text(ddl))
        conn.execute(text("CREATE TABLE price_records_default PARTITION OF price_records DEFAULT"))
        conn.execute(text(COPY_DATA))
        conn.execute(text(
        "SELECT setval(pg_get_serial_sequence('price_records', 'id'), "
        "(SELECT COALESCE(MAX(id), 1) FROM price_records_old))"
        ))
        conn.execute(text("DROP TABLE price_records_old"))
        conn.execute(text(
        "CREATE INDEX idx_price_crop_market_date ON price_records (crop_id, market_id, price_date DESC)"
        ))
        conn.execute(text("ANALYZE price_records"))
    print("Done: price_records ab quarterly partitions me hai.")


if __name__ == "__main__":
    main()
